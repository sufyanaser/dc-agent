// Generates every icon asset from the single SVG in relay/src/icon.ts (ICON_SVG).
// Outputs: assets/icon.ico (16..256), assets/icon-256.png, assets/icon.iconset/* (for macOS iconutil),
// and refreshes the ICO_BASE64 block in relay/src/icon.ts. Run: node scripts/make-icons.mjs
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PROJECT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ICON_TS = path.join(PROJECT, "relay", "src", "icon.ts");
const ASSETS = path.join(PROJECT, "assets");
const ICONSET = path.join(ASSETS, "icon.iconset");
const sharp = createRequire(path.join(PROJECT, "relay", "package.json"))("sharp");

const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256];
const ICONSET_FILES = [
  ["icon_16x16.png", 16], ["icon_16x16@2x.png", 32],
  ["icon_32x32.png", 32], ["icon_32x32@2x.png", 64],
  ["icon_128x128.png", 128], ["icon_128x128@2x.png", 256],
  ["icon_256x256.png", 256], ["icon_256x256@2x.png", 512],
  ["icon_512x512.png", 512], ["icon_512x512@2x.png", 1024],
];

const source = readFileSync(ICON_TS, "utf8");
const svgMatch = source.match(/export const ICON_SVG = `([^`]*)`;/);
if (!svgMatch) throw new Error("ICON_SVG not found in relay/src/icon.ts");
const svg = Buffer.from(svgMatch[1]);

const raster = new Map();
async function png(size) {
  if (!raster.has(size)) {
    // Render at 4x density first, then downscale, so small sizes keep a clean edge.
    raster.set(size, await sharp(svg, { density: 384 }).resize(size, size).png({ compressionLevel: 9 }).toBuffer());
  }
  return raster.get(size);
}

/** PNG-in-ICO container (supported by Windows Vista and later). */
function buildIco(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  const dir = Buffer.alloc(16 * images.length);
  let offset = 6 + dir.length;
  images.forEach(({ size, data }, i) => {
    const e = i * 16;
    dir[e] = size === 256 ? 0 : size;
    dir[e + 1] = size === 256 ? 0 : size;
    dir.writeUInt16LE(1, e + 4); // planes
    dir.writeUInt16LE(32, e + 6); // bits per pixel
    dir.writeUInt32LE(data.length, e + 8);
    dir.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, dir, ...images.map((i) => i.data)]);
}

mkdirSync(ICONSET, { recursive: true });
const ico = buildIco(await Promise.all(ICO_SIZES.map(async (size) => ({ size, data: await png(size) }))));
writeFileSync(path.join(ASSETS, "icon.ico"), ico);
writeFileSync(path.join(ASSETS, "icon-256.png"), await png(256));
for (const [name, size] of ICONSET_FILES) writeFileSync(path.join(ICONSET, name), await png(size));

const block = `// ICO-BEGIN (generated by scripts/make-icons.mjs, do not edit between the markers)\nconst ICO_BASE64 = "${ico.toString("base64")}";\n// ICO-END`;
const updated = source.replace(/\/\/ ICO-BEGIN[\s\S]*?\/\/ ICO-END/, () => block);
if (updated === source && !source.includes(block)) throw new Error("ICO markers not found in relay/src/icon.ts");
writeFileSync(ICON_TS, updated);

console.log(`icon.ico ${ico.length} bytes, ${ICO_SIZES.length} sizes; iconset ${ICONSET_FILES.length} files`);
